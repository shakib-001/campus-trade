-- Campus Trade Database Schema
-- Import this file directly in phpMyAdmin after creating the 'campus_trade' database

CREATE TABLE users (
  user_id INT AUTO_INCREMENT PRIMARY KEY,
  student_id VARCHAR(20),
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  phone VARCHAR(20),
  profile_pic VARCHAR(255),
  role ENUM('admin','student') DEFAULT 'student',
  status ENUM('active','blocked') DEFAULT 'active',
  reset_token VARCHAR(64) NULL,
  reset_expires DATETIME NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
  category_id INT AUTO_INCREMENT PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL
);

CREATE TABLE products (
  product_id INT AUTO_INCREMENT PRIMARY KEY,
  seller_id INT,
  category_id INT,
  title VARCHAR(150) NOT NULL,
  description TEXT,
  price DECIMAL(10,2),
  item_condition ENUM('new','used'),
  listing_type ENUM('sell','rent'),
  image VARCHAR(255),
  status ENUM('available','sold','removed') DEFAULT 'available',
  posted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (seller_id) REFERENCES users(user_id),
  FOREIGN KEY (category_id) REFERENCES categories(category_id)
);

CREATE TABLE requests (
  request_id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT,
  buyer_id INT,
  status ENUM('pending','accepted','rejected','completed') DEFAULT 'pending',
  meetup_location VARCHAR(150),
  meetup_time DATETIME,
  requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (product_id) REFERENCES products(product_id),
  FOREIGN KEY (buyer_id) REFERENCES users(user_id)
);

CREATE TABLE messages (
  message_id INT AUTO_INCREMENT PRIMARY KEY,
  sender_id INT,
  receiver_id INT,
  product_id INT,
  message_text TEXT,
  sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (sender_id) REFERENCES users(user_id),
  FOREIGN KEY (receiver_id) REFERENCES users(user_id)
);

CREATE TABLE reviews (
  review_id INT AUTO_INCREMENT PRIMARY KEY,
  reviewer_id INT,
  reviewed_user_id INT,
  request_id INT NULL,
  rating INT CHECK (rating BETWEEN 1 AND 5),
  comment TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (reviewer_id) REFERENCES users(user_id),
  FOREIGN KEY (reviewed_user_id) REFERENCES users(user_id),
  FOREIGN KEY (request_id) REFERENCES requests(request_id)
);

CREATE TABLE wishlist (
  wishlist_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT,
  product_id INT,
  FOREIGN KEY (user_id) REFERENCES users(user_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);

CREATE TABLE reports (
  report_id INT AUTO_INCREMENT PRIMARY KEY,
  reporter_id INT,
  product_id INT,
  reason TEXT,
  status ENUM('pending','reviewed') DEFAULT 'pending',
  reported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (reporter_id) REFERENCES users(user_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);

-- "Remember Me" tokens — selector/validator pattern (safe even if the DB ever leaked,
-- since only a hash of the validator is stored, never the raw token)
CREATE TABLE remember_tokens (
  token_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT,
  selector VARCHAR(64),
  hashed_validator VARCHAR(255),
  expires_at DATETIME,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(user_id)
);

-- Login attempts, used for rate-limiting brute-force login attempts
CREATE TABLE login_attempts (
  attempt_id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(100),
  ip_address VARCHAR(45),
  attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

